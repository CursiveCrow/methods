#!/usr/bin/env python3
"""Generate the per-part audit registers of the handbook tree (Ruling 6).

Usage: python tools/audit_tables.py [--root PATH]

Statically parses handbook/parts/**/*.tex (no compile required; the tree may
be half-built) for the nine theorem-class environments.  It writes one
theorem/definition booktabs longtable per part to
handbook/generated/audit-pNN.tex.  ``systementry`` cards are checked by the
handbook checker, but they are not published in these generated lookup views
until completed presentation packets supply an admission input.
Definition-class environments (hbdefinition/hbconvention/hbmethod/hbexample/
hbwarning/proofboundary) carry no status spec and render "--" in the Status
and Target columns; malformed status specs render as "invalid" with the raw
spec as target.  Output files are tool-owned: never hand-edit them.
"""

import argparse
import csv
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # keep tools/__pycache__ out of the repo
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check as chk  # noqa: E402  (shared static-parsing helpers)
import check_inherited_restoration as restoration  # noqa: E402
import build_source_unit_audit_crosswalk as source_units  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

HEADER_NOTE = "% Generated by tools/audit_tables.py -- do not hand-edit.\n"

ENTRY_FIELD_LABELS = {
    "entryaliases": "Aliases",
    "entrylanguage": "Language",
    "entrysemantics": "Semantics",
    "entrycalculus": "Calculus",
    "entryadequacy": "Adequacy",
    "entrydecidability": "Decidability",
    "entrycharacteristic": "Characteristic theorems and failures",
    "entrytranslations": "Translations",
    "entryalgebra": "Algebraic counterpart",
    "entrysources": "Sources",
}

SOURCE_ENVS = {
    "definition", "convention", "example", "warning",
    "theorem", "lemma", "corollary", "proposition",
}
SOURCE_STATUS_ENVS = {"theorem", "lemma", "corollary", "proposition"}


def reachable_part_files(root: Path, part: str) -> list[Path]:
    """Return one part's live input graph in reader order."""
    handbook = root / "handbook"
    start = handbook / "parts" / f"p{part}.tex"
    seen: set[Path] = set()
    ordered: list[Path] = []

    def visit(path: Path) -> None:
        path = path.resolve()
        if path in seen or not path.is_file():
            return
        seen.add(path)
        ordered.append(path)
        body = chk.strip_verbatims(chk.strip_comments(
            path.read_text(encoding="utf-8", errors="replace")))
        for match in re.finditer(r"\\input\s*\{([^{}]+)\}", body):
            rel = match.group(1).strip()
            if not rel.endswith(".tex"):
                rel += ".tex"
            visit(handbook / rel)

    visit(start)
    return ordered


def source_inventory(root: Path) -> dict[int, dict[str, str]]:
    """Map authoritative source start lines to their unit metadata."""
    path = root / "spec" / "source-unit-inventory.csv"
    with path.open(encoding="utf-8", newline="") as handle:
        return {
            int(row["start_line"]): row
            for row in csv.DictReader(handle)
            if row["start_line"]
        }


def source_record(root: Path, path: Path) -> dict | None:
    """Load validated provenance; a stale/missing source record stops generation."""
    match = re.fullmatch(r"inherited-(\d+)-(\d+)\.tex", path.name)
    if not match:
        return None
    records = list((root / "spec/provenance").glob(f"*-{match.group(1)}-{match.group(2)}.json"))
    if len(records) != 1:
        raise ValueError(f"{path}: exactly one restoration record is required for source locators")
    record = restoration.load_json(records[0])
    restoration.validate_record(record, records[0], root)
    if (root / record["restoration_artifact"]["path"]).resolve() != path.resolve():
        raise ValueError(f"{path}: restoration record names another artifact")
    return record


def source_line(path: Path, local_line: int, validated_map: dict[int, int | None] | None = None) -> int | None:
    """No filename-offset inference: only a validated unchanged span has a locator."""
    return validated_map.get(local_line) if validated_map is not None else None


def source_status(text: str) -> tuple[str, str]:
    """Read the mandatory status sentence of an exact-source result."""
    lowered = text.casefold()
    if "status: complete proof" in lowered:
        return "proved", "inline"
    if "status: proof sketch" in lowered:
        return "sketched", "reader-source"
    if "status: cited" in lowered:
        return "cited", "reader-source"
    return r"\textbf{unclassified}", "reader-source"


def longtable(colspec: str, header: list[str], body_rows: list[list[str]],
              size: str = r"\scriptsize", caption: str | None = None,
              label: str | None = None) -> str:
    """Booktabs longtable scaffold (mirrors tools/csv2tex.py)."""
    head = " & ".join(rf"\textbf{{{h}}}" for h in header) + r" \\"
    lines = [
        r"\begingroup" + size + r"\setlength{\tabcolsep}{3pt}",
        rf"\begin{{longtable}}{{{colspec}}}",
    ]
    if caption and label:
        lines.append(rf"\caption{{{caption}}}\label{{{label}}}\\")
    lines += [
        r"\toprule", head, r"\midrule", r"\endfirsthead",
        r"\toprule", head, r"\midrule", r"\endhead",
        r"\midrule\multicolumn{" + str(len(header)) +
        r"}{r}{\emph{continued}}\\\endfoot",
        r"\bottomrule\endlastfoot",
    ]
    for r in body_rows:
        lines.append(" & ".join(r) + r" \\")
    lines += [r"\end{longtable}", r"\endgroup"]
    return "\n".join(lines) + "\n"


def tt(s: str) -> str:
    """Typeset an identifier literally, with breaks after label punctuation."""
    chunks = []
    current = []
    for char in s:
        current.append(char)
        if char in ":-/":
            chunks.append("".join(current))
            current = []
    if current:
        chunks.append("".join(current))
    rendered = r"\allowbreak".join(
        rf"\detokenize{{{chunk}}}" for chunk in chunks)
    return rf"\texttt{{{rendered}}}"


def linked_tt(s: str) -> str:
    """Typeset a public identifier as a link to its reader destination."""
    return rf"\hyperref[{s}]{{{tt(s)}}}"


def display_title(title: str) -> str:
    """Strip the handbook.sty makeindex sort key: '<sort>@<display>' -> display."""
    depth = 0
    in_math = False
    index = 0
    while index < len(title):
        if title.startswith((r"\(", r"\["), index):
            in_math = True
            index += 2
            continue
        if title.startswith((r"\)", r"\]"), index):
            in_math = False
            index += 2
            continue
        char = title[index]
        if char == "\\":
            index += 2
            continue
        if char == "$":
            in_math = not in_math
        elif char == "{":
            depth += 1
        elif char == "}":
            depth = max(0, depth - 1)
        elif char == "@" and depth == 0 and not in_math:
            title = title[index + 1 :]
            break
        index += 1
    safe_commands = {
        r"\ZFC": r"\mathsf{ZFC}",
        r"\ZF": r"\mathsf{ZF}",
        r"\LK": r"\mathsf{LK}",
        r"\LJ": r"\mathsf{LJ}",
        r"\IPL": r"\mathsf{IPL}",
        r"\Sfive": r"\mathsf{S5}",
    }
    for source, replacement in safe_commands.items():
        title = title.replace(source, replacement)
    return title


def collect(root: Path, *, candidate_corrections: set[str] | None = None,
            corrected_labels: dict[str, set[str]] | None = None,
            corrected_artifact_hashes: dict[str, str] | None = None) -> dict[str, list[list[str]]]:
    """Map part number to rows from that part's live reader graph."""
    base = root / "handbook" / "parts"
    parts: dict[str, list[list[str]]] = {}
    if not base.is_dir():
        return parts
    inventory = source_inventory(root)
    env_names = sorted(set(chk.HB_THEOREM_CLASS) | SOURCE_ENVS)
    env_re = re.compile(
        r"\\begin\{(" + "|".join(env_names) + r")\}(?:\[([^\]]*)\])?")
    for root_path in sorted(base.glob("p[0-9][0-9].tex")):
        part = root_path.stem[1:]
        rows: list[list[str]] = []
        source_anchor = 0
        for path in reachable_part_files(root, part):
            provenance = source_record(root, path)
            original_lines = restoration.reader_source_line_map(provenance) if provenance else {}
            corrected_reader = provenance is not None and provenance["schema_version"] == 4
            if corrected_reader and candidate_corrections is not None:
                candidate_corrections.add(provenance["provenance_id"])
            if corrected_reader and corrected_artifact_hashes is not None:
                corrected_artifact_hashes[provenance["provenance_id"]] = provenance["restoration_artifact"]["sha256"]
            raw = path.read_bytes()
            if provenance and restoration.sha256(raw) != provenance["restoration_artifact"]["sha256"]:
                raise ValueError(f"{path}: reader bytes changed after source mapping validation")
            text = raw.decode("utf-8", errors="replace").replace("\r\n", "\n").replace("\r", "\n")
            body = chk.strip_verbatims(chk.strip_comments(text))
            for em in env_re.finditer(body):
                env = em.group(1)
                if env in chk.HB_THEOREM_CLASS:
                    if env in chk.HB_STATUS_ENVS:
                        args, _ = chk.scan_braced_args(body, em.end(), 3)
                        label = args[0].strip() if args else "??"
                        title = args[2].strip() if len(args) >= 3 else "??"
                        spec = args[1] if len(args) >= 2 else ""
                        parsed = chk.hb_parse_status(spec)
                        if parsed is None:
                            form = r"\textbf{invalid}"
                            target = tt(spec.strip()[:40]) if spec.strip() else "--"
                        else:
                            form = parsed[0]
                            target = tt(parsed[1])
                    else:
                        args, _ = chk.scan_braced_args(body, em.end(), 2)
                        label = args[0].strip() if args else "??"
                        title = args[1].strip() if len(args) >= 2 else "??"
                        form = target = "--"
                else:
                    end = body.find(rf"\end{{{env}}}", em.end())
                    if end < 0:
                        end = len(body)
                    unit = body[em.end():end]
                    local_line = body.count("\n", 0, em.start()) + 1
                    absolute = source_line(path, local_line, original_lines)
                    meta = inventory.get(absolute or -1, {})
                    auto_label = ""
                    if part in {"06", "07", "08"} and provenance is not None:
                        source_anchor += 1
                        auto_label = f"entry:p{part}-source-{source_anchor}"
                    label_match = re.search(r"\\label\{([^{}]+)\}", unit)
                    label = (
                        label_match.group(1).strip() if label_match
                        else meta.get("label", "").strip() or auto_label
                    )
                    title = (
                        meta.get("title", "").strip()
                        or (em.group(2) or "").strip()
                        or env.capitalize()
                    )
                    if env in SOURCE_STATUS_ENVS:
                        form, source_target = source_status(unit)
                        after = body[end + len(rf"\end{{{env}}}"):]
                        if (form == r"\textbf{unclassified}"
                                and re.match(r"\s*\\begin\{proof\}", after)):
                            form, source_target = "proved", "inline"
                        elif (form == r"\textbf{unclassified}" and re.match(
                                r"\s*\\paragraph\{Proof sketch\.\}",
                                after)):
                            form, source_target = "sketched", "reader-source"
                        if (form == r"\textbf{unclassified}"
                                and label == "lem:relativization-derivations"):
                            form, source_target = "proved", "inline"
                        target = {
                            "inline": (r"\textit{inline reader proof}" if corrected_reader
                                       else r"\textit{inline source proof}"),
                            "reader-source": (r"\textit{reader status}" if corrected_reader
                                              else r"\textit{source status}"),
                        }[source_target]
                    else:
                        form = target = "--"
                shown_label = linked_tt(label) if label and label != "??" else "--"
                if corrected_reader and corrected_labels is not None:
                    corrected_labels.setdefault(provenance["provenance_id"], set()).add(label)
                rows.append([
                    shown_label, display_title(title), form, target
                ])
        parts[part] = rows
    return parts


def _entry_metadata(name: str, args: list[str]) -> str:
    """Render one card field without reclassifying it as a theorem status."""
    if name in ("entryadequacy", "entrydecidability"):
        spec = args[0].strip() if args else ""
        text = args[1].strip() if len(args) >= 2 else ""
        parsed = chk.hb_parse_status(spec)
        if parsed is None:
            status = rf"\textbf{{invalid status}} {tt(spec) if spec else '--'}"
        else:
            status = rf"\textit{{{parsed[0]}}} $\to$ {tt(parsed[1])}"
        return status + (rf"\enspace {text}" if text else "")
    value = args[0].strip() if args else ""
    if not value:
        return r"\textbf{empty}"
    if name == "entrycalculus":
        return tt(value)
    if name == "entrysources":
        keys = [key.strip() for key in value.split(",") if key.strip()]
        return ", ".join(tt(key) for key in keys) or r"\textbf{empty}"
    return value


def collect_entry_cards(root: Path) -> dict[str, list[list[str]]]:
    """Map part number to complete card-field rows, separate from results."""
    base = root / "handbook" / "parts"
    parts: dict[str, list[list[str]]] = {}
    if not base.is_dir():
        return parts
    env_re = re.compile(r"\\begin\{systementry\}")
    field_re = re.compile(
        r"\\(" + "|".join(chk.HB_ENTRY_FIELDS_ALL) + r")\b")
    for path in sorted(base.rglob("*.tex")):
        rel = path.relative_to(root / "handbook").as_posix()
        pm = re.match(r"parts/p(\d{2})", rel)
        if not pm:
            continue
        part = pm.group(1)
        parts.setdefault(part, [])
        raw = path.read_text(encoding="utf-8", errors="replace")
        body = chk.strip_verbatims(chk.strip_comments(raw))
        for em in env_re.finditer(body):
            args, args_end = chk.scan_braced_args(body, em.end(), 2)
            label = args[0].strip() if args else "??"
            title = args[1].strip() if len(args) >= 2 else "??"
            end = body.find(r"\end{systementry}", args_end)
            if end == -1:
                end = len(body)
            n_fields = 0
            for fm in field_re.finditer(body, args_end, end):
                name = fm.group(1)
                arity = 2 if name in (
                    "entryadequacy", "entrydecidability") else 1
                fargs, _ = chk.scan_braced_args(body, fm.end(), arity)
                parts[part].append([
                    tt(label or "??"),
                    display_title(title),
                    ENTRY_FIELD_LABELS[name],
                    _entry_metadata(name, fargs),
                ])
                n_fields += 1
            if not n_fields:
                parts[part].append([
                    tt(label or "??"),
                    display_title(title),
                    "--",
                    r"\textbf{no fields harvested}",
                ])
    return parts


def render_part(part: str, rows: list[list[str]],
                card_rows: list[list[str]]) -> str:
    """Render one deterministic generated audit/reference file."""
    blocks: list[str] = []
    if card_rows:
        blocks.append(r"\noindent\textbf{Theorem and definition records.}\par")
    if not rows:
        rows = [["--", f"No theorem-class results in Part~{int(part)} yet.",
                 "--", "--"]]
    blocks.append(longtable(
        r"@{}p{0.26\textwidth}p{0.40\textwidth}p{0.11\textwidth}p{0.17\textwidth}@{}",
        ["ID", "Title", "Status", "Target"], rows,
        caption=f"Theorem and definition register for Part {int(part)}.",
        label=f"tab:p{part}-theorem-definition-register"))
    if card_rows:
        blocks.append(
            r"\medskip\noindent\textbf{System entry card metadata.}\par")
        blocks.append(longtable(
            r"@{}p{0.20\textwidth}p{0.22\textwidth}p{0.18\textwidth}p{0.34\textwidth}@{}",
            ["Entry", "System", "Card field", "Metadata"], card_rows))
    return HEADER_NOTE + "\n".join(blocks)


def emit(root: Path, parts: dict[str, list[list[str]]],
         entry_parts: dict[str, list[list[str]]] | None = None) -> int:
    out = root / "handbook" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    entry_parts = entry_parts or {}
    written = 0
    for part in sorted(set(parts) | set(entry_parts)):
        rows = parts.get(part, [])
        card_rows = entry_parts.get(part, [])
        path = out / f"audit-p{part}.tex"
        content = render_part(part, rows, card_rows)
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        written += 1
        print(f"[audit] p{part}: {len(rows)} theorem/definition row(s), "
              f"{len(card_rows)} card-metadata row(s) -> "
              f"{path.relative_to(root).as_posix()}")
    return written


def check_freshness(root: Path, parts: dict[str, list[list[str]]],
                    entry_parts: dict[str, list[list[str]]] | None = None) -> int:
    """Return nonzero if any expected audit file is missing or stale."""
    out = root / "handbook" / "generated"
    entry_parts = entry_parts or {}
    stale: list[Path] = []
    for part in sorted(set(parts) | set(entry_parts)):
        path = out / f"audit-p{part}.tex"
        expected = render_part(
            part, parts.get(part, []), entry_parts.get(part, []))
        if (not path.is_file()
                or path.read_text(encoding="utf-8", errors="replace") != expected):
            stale.append(path)
    if stale:
        print(f"[audit] {len(stale)} missing/stale generated file(s):",
              file=sys.stderr)
        for path in stale:
            try:
                shown = path.relative_to(root).as_posix()
            except ValueError:
                shown = str(path)
            print(f"  - {shown}", file=sys.stderr)
        return 1
    print(f"[audit] freshness check passed for "
          f"{len(set(parts) | set(entry_parts))} file(s)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="repo root override (used by the fixture self-tests)")
    ap.add_argument("--check", action="store_true",
                    help="verify generated audit files without rewriting them")
    args = ap.parse_args()
    root = Path(args.root).resolve()
    if not (root / "handbook").is_dir():
        print(f"[audit] no handbook tree at {root / 'handbook'}", file=sys.stderr)
        return 2
    candidate_corrections: set[str] = set()
    corrected_labels: dict[str, set[str]] = {}
    corrected_artifact_hashes: dict[str, str] = {}
    try:
        parts = collect(root, candidate_corrections=candidate_corrections,
                        corrected_labels=corrected_labels,
                        corrected_artifact_hashes=corrected_artifact_hashes)
        if candidate_corrections:
            source_units.require_corrected_reader_admissions(
                root, candidate_corrections, corrected_labels, corrected_artifact_hashes)
    except (OSError, ValueError) as exc:
        print(f"[audit] active output blocked: source mapping or terminal admission input validation failed: {exc}", file=sys.stderr)
        return 1
    # Architecture section 3 permits system-card lookup views only from
    # completed presentation packets.  The repository currently has no
    # packet-admission input, so source-tree cards must not flow into a
    # reader-facing generated table merely because their fields parse.
    entry_parts: dict[str, list[list[str]]] = {}
    if not parts:
        print("[audit] no parts found under handbook/parts (half-built tree?)")
        return 0
    if args.check:
        return check_freshness(root, parts, entry_parts)
    n = emit(root, parts, entry_parts)
    result_total = sum(len(r) for r in parts.values())
    card_total = sum(len(r) for r in entry_parts.values())
    print(f"[audit] wrote {n} file(s), {result_total} theorem/definition "
          f"row(s), {card_total} card-metadata row(s) total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
